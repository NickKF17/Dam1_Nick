console.log("Resta:", a - b); // sustracción
console.log("Multiplicación:", a * b); // multiplicación
console.log("División:", a / b); // división
console.log("Módulo:", a % b); // módulo o residuo
console.log("Exponenciación:", a ** b); // exponenciación (a elevado a la potencia de b)

