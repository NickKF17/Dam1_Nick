//bitwise operators
//bit:0 y 1
//BYTES: 8 bits = 1 byte
//byte: 00000000 -> 0
//byte: 11111111 -> 255

console.log(5 & 3); // 1, porque 5 en binario es 101 y 3 en binario es 011, entonces el resultado de la operación AND es 001, que es 1 en decimal
console.log(5 | 3); // 7, porque 5 en binario es 101 y 3 en binario es 011, entonces el resultado de la operación OR es 111, que es 7 en decimal