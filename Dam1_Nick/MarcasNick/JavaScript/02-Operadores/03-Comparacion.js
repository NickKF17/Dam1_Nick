let a =10;

console.log(a == 10); // true, porque el valor de a es igual a 10
console.log(a < 20); // true, porque el valor de a es menor que 20
console.log(a > 5); // true, porque el valor de a es mayor que 5
console.log(a <= 10); // true, porque el valor de a es menor o igual a 10
console.log(a >= 15); // false, porque el valor de a no es mayor o igual a 15
console.log(a != 5); // true, porque el valor de a no es igual a 5  

console.log(a ===  '10'); // false, porque el valor de a es un número y '10' es una cadena (comparación estricta)
console.log(a !== '10'); // true, porque el valor de a es un número y '10' es una cadena (comparación estricta)